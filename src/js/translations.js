let currentLang = 'it';
function getLang() { return currentLang; }
function setLang(lang) {
    if (!translations[lang]) return false;
    currentLang = lang;
    return true;
}

// Interpolazione semplice: t('status_saved', { time: '14:30' }) → '✓ Salvato 14:30'
function t(key, vars) {
    let s = translations[currentLang]?.[key] ?? translations.it[key] ?? key;
    if (vars) for (const k in vars) s = s.replace('{' + k + '}', vars[k]);
    return s;
}
